const R = (x: number, y: number, w: number, h: number) => `M${x} ${y}h${w}v${h}h${-w}Z`;
const C = (x: number, y: number, r: number) => `M${x - r} ${y}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
const E = (x: number, y: number, rx: number, ry: number) => `M${x - rx} ${y}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`;
const L = (...p: number[]) => 'M' + p.map((v, i) => (i % 2 ? v + ' ' : (i ? 'L' : '') + v + ' ')).join('').trim();
const Z = (...p: number[]) => L(...p) + 'Z';
/** A gear of n teeth round (x, y). */
function gear(x: number, y: number, r: number, n: number): string {
  const pts: number[] = [];
  for (let i = 0; i < n * 4; i++) { const a = (i / (n * 4)) * Math.PI * 2, rr = i % 4 < 2 ? r : r * 0.78; pts.push(+(x + Math.cos(a) * rr).toFixed(2), +(y + Math.sin(a) * rr).toFixed(2)); }
  return Z(...pts) + C(x, y, r * 0.3);
}
